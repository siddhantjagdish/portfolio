export const getScheme = (id) => schemes.find((s) => s.id === id)

// Realized distribution yield, trailing twelve months (average of 4 quarters).
export const ttmYield = (s) =>
  s.yieldRealized.length ? s.yieldRealized.reduce((a, b) => a + b, 0) / s.yieldRealized.length : null

export const avgProjected = (s) => s.yieldProjected.reduce((a, b) => a + b, 0) / s.yieldProjected.length

export const currentOccupancy = (s) => s.occupancyHistory[s.occupancyHistory.length - 1]

export const totalFeeDrag = (s) => s.fees.management + s.fees.trustee + s.fees.platform

export const navGapPct = (s) => ((s.unitPrice - s.nav) / s.nav) * 100

// Largest single non-aggregate tenant, for concentration flags.
export const topTenant = (s) => {
  const named = s.tenants.filter((t) => !t.aggregate)
  if (!named.length) return null
  return named.reduce((a, b) => (a.rentShare >= b.rentShare ? a : b))
}

